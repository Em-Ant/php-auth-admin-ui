/** Compact rendering for TTL seconds: 300 -> "5m", 86400 -> "1d". */
export const formatTtl = (seconds: number) => {
  if (seconds % 86400 === 0) {
    return `${seconds / 86400}d`;
  }
  if (seconds % 3600 === 0) {
    return `${seconds / 3600}h`;
  }
  if (seconds % 60 === 0) {
    return `${seconds / 60}m`;
  }
  return `${seconds}s`;
};
